def main():
    rows = []
    sid = 21
    for scene, loops in SCENE_LOOPS.items():
        for i in range(14):
            loop, key = loops[i % len(loops)]
            target = 6 if i % 2 == 0 else 8
            cb = 3 + (i % 3)
            rows.append({
                "seed_id": "p%03d" % sid,
                "scene": scene,
                "time": TIMES[i],
                "her_state": HERS[i],
                "user_state": USERS[i],
                "open_loop": loop,
                "target_turns": target,
                "callback_turn": cb,
                "callback_key": key,
                "tone": TONES[i],
            })
            sid += 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n")
    print("rows", len(rows), "first", rows[0]["seed_id"], "last", rows[-1]["seed_id"])


if __name__ == "__main__":
    main()
